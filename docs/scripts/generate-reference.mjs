import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { repository, siteBase } from "../site.mjs";

const site = fileURLToPath(new URL("../", import.meta.url));
const repo = resolve(site, "..");
const generated = join(site, "src", "content", "docs", "reference");
const header = "---\n# Generated by generate-reference.mjs\n";
const windows = process.platform === "win32";
const executable = windows ? "lyra.exe" : "lyra";

function readReference() {
  const presets = windows ? ["windows-dev", "windows-release"] : ["dev", "release"];
  const local = presets.map((preset) => join(repo, "build", preset, "bin", executable));
  const override = process.env.LYRA_DOC_COMPILER;
  const compiler = override ? resolve(override) : local.find(existsSync) ?? executable;
  let json;
  try {
    json = execFileSync(compiler, ["doc", "--stdlib"], {
      cwd: repo,
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    });
  } catch (error) {
    throw new Error(
      `无法运行 ${compiler} doc --stdlib。请重新构建当前工作区的 Lyra，或设置 LYRA_DOC_COMPILER 指向对应的编译器。`,
      { cause: error },
    );
  }
  const data = JSON.parse(json);
  const version = readFileSync(join(repo, "VERSION"), "utf8").trim();
  if (data.schemaVersion !== 1 || !data.syntax) throw new Error("需要包含语法速查的 Lyra 参考数据 JSON v1。");
  if (data.compilerVersion !== version) {
    throw new Error(`Lyra 版本不匹配：编译器是 ${data.compilerVersion}，工作区需要 ${version}。`);
  }
  return { data, json };
}

function fence(text, minimum) {
  return "`".repeat(Math.max(minimum, ...[...text.matchAll(/`+/g)].map(([run]) => run.length + 1)));
}

function code(text) {
  const ticks = fence(text, 1);
  return `${ticks} ${text} ${ticks}`;
}

function signature(text) {
  const ticks = fence(text, 3);
  return `${ticks}lyra\n${text}\n${ticks}`;
}

function slug(name) {
  if (!/^[A-Za-z][A-Za-z0-9_-]*(?:\.[A-Za-z][A-Za-z0-9_-]*)*$/.test(name)) {
    throw new Error(`无效的参考页名称：${name}`);
  }
  return name.toLowerCase().replaceAll(".", "-");
}

function anchor(id) {
  return "api-" + createHash("sha256").update(id).digest("hex").slice(0, 20);
}

function link(from, target, label, hash = "") {
  const relative = posix.relative(`/reference/${from}`, `/reference/${target}`);
  const href = (relative ? `${relative}/` : "") + (hash ? `#${hash}` : "");
  return `[${label}](${href || "./"})`;
}

function sourceLink(source) {
  const revision = process.env.GITHUB_SHA || "main";
  const location = [source.package.slice(4), ...source.file.split("/")].map(encodeURIComponent).join("/");
  return `${repository}/blob/${encodeURIComponent(revision)}/std/${location}#L${source.line}`;
}

const builtinTypes = new Set(["type", "typeAlias", "enum", "exception", "trait"]);
const contexts = { async: "仅能在异步执行体中调用。", macro: "仅用于宏实现。", unsafe: "需要在 `unsafe` 块中使用。" };

function renderReference(data) {
  const pages = new Map();
  const entries = new Map();
  const children = new Map();
  const byModule = new Map(data.modules.map(({ name }) => [name, []]));
  for (const entry of data.entries) {
    if (entries.has(entry.id)) throw new Error(`重复的 Lyra API ID：${entry.id}`);
    entries.set(entry.id, entry);
    if (entry.ownerId) {
      if (!children.has(entry.ownerId)) children.set(entry.ownerId, []);
      children.get(entry.ownerId).push(entry);
    } else byModule.get(entry.module).push(entry);
  }
  const standard = [...byModule.keys()].filter((name) => name.startsWith("std."));
  const stdRoute = (name) => `std/${slug(name.slice(4))}`;
  const builtins = byModule.get("builtin");
  const routes = new Map();
  const register = (entry, route) => {
    routes.set(entry.id, route);
    for (const member of children.get(entry.id) || []) register(member, route);
  };
  for (const entry of builtins) {
    const route = builtinTypes.has(entry.kind) ? `builtins/types/${slug(entry.name)}` : "builtins";
    register(entry, route);
  }
  for (const module of standard) for (const entry of byModule.get(module)) register(entry, stdRoute(module));
  if (routes.size !== entries.size) throw new Error("Lyra 参考数据中有条目未关联到模块或类型。");

  const add = (route, title, body, order, toc = 2) => {
    if (pages.has(route)) throw new Error(`重复的参考页路由：${route}`);
    const file = !route || route === "std" ? posix.join(route, "index.md") : `${route}.md`;
    const settings = [
      `title: ${JSON.stringify(title)}`,
      "editUrl: false",
      "prev: false",
      "next: false",
      toc ? `tableOfContents: { minHeadingLevel: 2, maxHeadingLevel: ${toc} }` : "tableOfContents: false",
      ...(order === undefined ? [] : [`sidebar: { order: ${order} }`]),
    ];
    pages.set(route, { file, body: `${header}${settings.join("\n")}\n---\n\n${body}\n` });
  };

  const entryLink = (from, entry, label = entry.name) => link(from, routes.get(entry.id), code(label), anchor(entry.id));
  const renderEntry = (entry, depth, heading = true) => {
    const route = routes.get(entry.id);
    const id = anchor(entry.id);
    const blocks = [`<span id="${id}"></span>`];
    if (heading) blocks.push(`${"#".repeat(Math.min(depth, 6))} ${code(entry.name)}`);
    blocks.push(signature(entry.signature));
    if (entry.implementationSignature) blocks.push("**编译期入口**", signature(entry.implementationSignature));
    if (entry.documentation) blocks.push(entry.documentation);
    if (entry.context && contexts[entry.context]) blocks.push(contexts[entry.context]);
    const parameters = entry.parameters.filter((param) => param.documentation);
    if (parameters.length) blocks.push(parameters.map((param) => `- ${code(param.name)}：${param.documentation.replaceAll("\n", "\n  ")}`).join("\n"));
    const metadata = [];
    if (entry.source) metadata.push(`[${entry.generated ? "宏调用位置" : "源码"}](${sourceLink(entry.source)})`);
    const origin = entries.get(entry.originId);
    if (origin) metadata.push(`重导出自 ${entryLink(route, origin, origin.qualifiedName)}`);
    if (metadata.length) blocks.push(metadata.join(" · "));
    for (const member of children.get(entry.id) || []) blocks.push(renderEntry(member, heading ? depth + 1 : depth));
    return blocks.join("\n\n");
  };

  add("", "参考总览", [
    `Lyra ${code(data.compilerVersion)} 的语法、内置 API 和标准库接口。${data.missingDocumentation.length ? `有 ${data.missingDocumentation.length} 个条目尚无说明。` : ""}`,
    "- [语法速查](syntax/)：关键字、运算符优先级和结合性。",
    "- [编译器内置](builtins/)：类型、全局函数和宏实现可用的接口。",
    "- [标准库](std/)：按模块查找公开类型、函数和扩展。",
    `<a href="${siteBase.replace(/\/$/, "")}/reference.json" download>下载参考数据（JSON）</a>`,
  ].join("\n\n"), undefined, false);

  const form = { infix: "中缀", prefix: "前缀", postfix: "后缀" };
  const association = { left: "左结合", right: "右结合", none: "不结合" };
  const operators = new Map();
  for (const op of data.syntax.operators) {
    const key = `| ${op.precedence} | ${form[op.fixity] ?? op.fixity} | ${association[op.associativity] ?? op.associativity} |`;
    if (!operators.has(key)) operators.set(key, []);
    operators.get(key).push(code(op.spelling.replaceAll("|", "\\|")));
  }
  add("syntax", "语法速查", [
    "## 保留关键字", data.syntax.keywords.map(code).join("、"),
    "## 上下文关键字", "这些词只在特定语法位置具有特殊含义。", data.syntax.contextualKeywords.map(code).join("、"),
    "## 运算符优先级", "表格从低到高排列；优先级越高，绑定越紧。",
    ["| 优先级 | 形式 | 结合性 | 运算符 |", "| --- | --- | --- | --- |",
      ...[...operators].map(([base, spellings]) => `${base} ${spellings.join("、")} |`)].join("\n"),
  ].join("\n\n"));

  add("std", "标准库索引", standard.map((module) => `- ${link("std", stdRoute(module), code(module))}`).join("\n"), 0, false);
  for (const module of standard) {
    add(stdRoute(module), module, byModule.get(module).map((entry) => renderEntry(entry, 2)).join("\n\n"));
  }

  const types = builtins.filter((entry) => builtinTypes.has(entry.kind));
  const functions = builtins.filter((entry) => !builtinTypes.has(entry.kind) && entry.context !== "macro");
  const macroApi = builtins.filter((entry) => !builtinTypes.has(entry.kind) && entry.context === "macro");
  const list = (items) => items.map((entry) => `- ${entryLink("builtins", entry)}`).join("\n");
  add("builtins", "编译器内置索引", [
    "这些类型和接口由编译器提供，不需要导入 `std` 模块。",
    "## 类型与约束", list(types.filter((entry) => entry.context !== "macro")),
    "## 全局函数", ...functions.map((entry) => renderEntry(entry, 3)),
    "## 宏 API", list(types.filter((entry) => entry.context === "macro")), ...macroApi.map((entry) => renderEntry(entry, 3)),
  ].filter(Boolean).join("\n\n"));
  const extensions = data.entries.filter((entry) => entry.kind === "extension" && !entry.originId);
  for (const entry of types) {
    const route = routes.get(entry.id);
    const related = extensions.filter(({ receiver }) => receiver === entry.name || receiver?.startsWith(`${entry.name}<`));
    const body = [renderEntry(entry, 2, false)];
    if (related.length) body.push("## 标准库扩展", related.map((item) => `- ${entryLink(route, item, item.qualifiedName)}`).join("\n"));
    add(route, entry.name, body.join("\n\n"));
  }
  return [...pages.values()];
}

function publish(pages, json) {
  mkdirSync(generated, { recursive: true });
  const expected = new Set(pages.map(({ file }) => join(generated, file)));
  for (const { file, body } of pages) {
    const path = join(generated, file);
    if (existsSync(path)) {
      const current = readFileSync(path, "utf8");
      if (!current.startsWith(header)) throw new Error(`参考页会覆盖手写文档：${path}`);
      if (current === body) continue;
    }
    mkdirSync(resolve(path, ".."), { recursive: true });
    writeFileSync(path, body);
  }
  for (const entry of readdirSync(generated, { recursive: true, withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
    const path = join(entry.parentPath, entry.name);
    if (!expected.has(path) && readFileSync(path, "utf8").startsWith(header)) rmSync(path);
  }
  writeFileSync(join(site, "public", "reference.json"), json);
}

const { data, json } = readReference();
const pages = renderReference(data);
publish(pages, json);
console.log(`Lyra ${data.compilerVersion}：生成 ${pages.length} 个参考页面，收录 ${data.entries.length} 个 API 条目。`);
